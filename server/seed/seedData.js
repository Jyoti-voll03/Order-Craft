async function seedDatabase(closeConnection = false) {
  await Promise.all([
    Order.deleteMany({}),
    Production.deleteMany({}),
    Inventory.deleteMany({}),
    Customer.deleteMany({}),
    User.deleteMany({}),
  ]);

  const enrichedInventory = demoInventory.map((item) => ({
    ...item,
    stockStatus: computeStockStatus(item.quantity, item.minimumStock),
  }));

  await Customer.insertMany(demoCustomers);
  await Order.insertMany(demoOrders);
  await Production.insertMany(demoProduction);
  await Inventory.insertMany(enrichedInventory);

  // Create default Admin and Manager users (passwords hashed via User model pre-save)
  await User.create({
    name: 'Aarav Deshmukh',
    email: 'admin@ordercraft-mfg.in',
    password: 'password123',
    role: 'admin',
  });

  await User.create({
    name: 'Rajesh Sharma',
    email: 'manager@ordercraft-mfg.in',
    password: 'password123',
    role: 'manager',
  });

  if (closeConnection) {
    await mongoose.connection.close();
  }

  return {
    customers: demoCustomers.length,
    orders: demoOrders.length,
    production: demoProduction.length,
    inventory: enrichedInventory.length,
    users: 2,
  };
}

// Allow running directly via `npm run seed`
if (require.main === module) {
  const { connectDB } = require('../config/db');
  (async () => {
    try {
      await connectDB();
      const stats = await seedDatabase(true);
      console.log('OrderCraft Database Seeded Successfully:', stats);
      process.exit(0);
    } catch (err) {
      console.error('Error seeding database:', err);
      process.exit(1);
    }
  })();
}

